  def _find_body(self, names):
    # Respect caller priority.  Scanning model order first selected pelvis
    # before torso_link because pelvis appears earlier in the body tree.
    model_names = [
      mj.mj_id2name(self.native_model, mj.mjtObj.mjOBJ_BODY, body_id)
      for body_id in range(self.native_model.nbody)
    ]
    for requested_name in names:
      requested = requested_name.lower()
      for body_id, model_name in enumerate(model_names):
        if model_name and (
          model_name.lower() == requested
          or model_name.lower().endswith(requested)
        ):
          return body_id
    for requested_name in names:
      requested = requested_name.lower()
      for body_id, model_name in enumerate(model_names):
        if model_name and requested in model_name.lower():
          return body_id
    return -1

  def _sync_anchor_visual(self, sim):
    """Move the non-physical anchor marker and visual tendon to this profile."""
    if self.anchor_visual_body_id < 0:
      print("[WIRE][WARN] anchor_visual body was not found", flush=True)
      return

    # Native MuJoCo is used by the viewer/model topology, while MJWarp performs
    # the simulation.  Update both representations in place so ascend and
    # descend modes display the same anchor used by the force controller.
    self.native_model.body_pos[self.anchor_visual_body_id] = self.anchor_pos
    mj.mj_forward(self.native_model, sim.mj_data)
    body_pos = sim.model.body_pos
    target = (
      body_pos[0, self.anchor_visual_body_id]
      if len(body_pos.shape) == 3
      else body_pos[self.anchor_visual_body_id]
    )
    target.copy_(
      torch.as_tensor(
        self.anchor_pos,
        device=target.device,
        dtype=target.dtype,
      )
    )
    sim.forward()
    print(
      f"[WIRE] visual anchor synchronized to {tuple(self.anchor_pos)}",
      flush=True,
    )

  def _find_site(self, requested_name):
    for site_id in range(self.native_model.nsite):
      name = mj.mj_id2name(self.native_model, mj.mjtObj.mjOBJ_SITE, site_id)
      if name and (name == requested_name or name.endswith(requested_name)):
        return site_id
    return -1

  def _find_joint(self, requested_name):
    for joint_id in range(self.native_model.njnt):
      name = mj.mj_id2name(self.native_model, mj.mjtObj.mjOBJ_JOINT, joint_id)
      if name and (name == requested_name or name.endswith(requested_name)):
        return joint_id
    return -1

