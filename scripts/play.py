  def _build_posture_action(self, desired):
    action_manager = getattr(self.env.unwrapped, "action_manager", None)
    if action_manager is None:
      return None
    try:
      term = action_manager.get_term("joint_pos")
      names, offset, scale = term.target_names, term.offset, term.scale
    except (KeyError, AttributeError):
      return None

    posture = torch.zeros_like(term.raw_action)
    for index, name in enumerate(names):
      requested_name = next(
        (
          candidate
          for candidate in desired
          if name == candidate or name.endswith(candidate)
        ),
        None,
      )
      if requested_name is None:
        continue
      joint_offset = offset[:, index] if hasattr(offset, "ndim") else offset
      joint_scale = scale[:, index] if hasattr(scale, "ndim") else scale
      posture[:, index] = (desired[requested_name] - joint_offset) / joint_scale
    return torch.clamp(
      posture, -self.posture_action_limit, self.posture_action_limit
    )

  def _rate_limit_action(self, target, previous, rate_limit, indices=None):
    """Limit normalized joint-action motion to ``rate_limit`` per second."""
    if previous is None or rate_limit is None or rate_limit <= 0.0:
      return target
    previous = previous.to(device=target.device, dtype=target.dtype)
    max_delta = float(rate_limit) * self.dt
    if indices is None:
      return previous + torch.clamp(target - previous, -max_delta, max_delta)
    limited = target.clone()
    limited[:, indices] = previous[:, indices] + torch.clamp(
      target[:, indices] - previous[:, indices], -max_delta, max_delta
    )
    return limited

