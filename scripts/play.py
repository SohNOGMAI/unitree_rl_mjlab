  @staticmethod
  def _numpy(value):
    return value.detach().cpu().numpy() if hasattr(value, "detach") else np.asarray(value)

  def _env0(self, value, item_id):
    array = self._numpy(value)
    return np.array(array[0, item_id] if array.ndim == 3 else array[item_id], copy=True)

  def _scalar_env0(self, value, item_id):
    array = self._numpy(value)
    return float(array[0, item_id] if array.ndim == 2 else array[item_id])

  @staticmethod
  def _wrap_to_pi(angle):
    return (angle + np.pi) % (2.0 * np.pi) - np.pi

  def _set_walking_command(
    self,
    yaw=None,
    lateral_position=None,
    allow_forward=True,
    forward_scale=1.0,
  ):
    """Track the +x path without applying a yaw command.

    The velocity policy uses body-frame commands.  A small body-frame lateral
    command is therefore computed from the world-frame y error while walking.
    This keeps the robot below the fixed anchor plane without reintroducing the
    aggressive yaw controller that previously excited the upper body.
    """
    command_manager = getattr(self.env.unwrapped, "command_manager", None)
    if command_manager is None:
      return False
    try:
      command = command_manager.get_command("twist")
      self.heading_aligned = True
      self.heading_error = 0.0
      forward_world = (
        self.lin_vel_x * float(np.clip(forward_scale, 0.0, 1.0))
        if allow_forward
        else 0.0
      )
      lateral_world = 0.0
      if allow_forward and lateral_position is not None:
        lateral_world = float(
          np.clip(
            self.lateral_position_kp
            * (self.anchor_pos[1] - float(lateral_position)),
            -self.max_lateral_speed,
            self.max_lateral_speed,
          )
        )
      heading = float(yaw or 0.0)
      c, s = np.cos(heading), np.sin(heading)
      target = torch.tensor(
        [
          c * forward_world + s * lateral_world,
          -s * forward_world + c * lateral_world,
          0.0,
        ],
        device=command.device,
        dtype=command.dtype,
      )
      with torch.no_grad():
        command[:] = target
    except (KeyError, AttributeError):
      return False
    return True

  def _obstacle_bounds(self):
    geom_xpos = getattr(self.mj_data, "geom_xpos", None)
    center = (
      self._env0(geom_xpos, self.obstacle_geom_id)
      if geom_xpos is not None
      else self._env0(self.mj_data.xpos, self.obstacle_body_id)
    )
    half_size = np.asarray(self.native_model.geom_size[self.obstacle_geom_id])
    # The research setup assumes an axis-aligned rectangular obstacle in x-z.
    return (
      center[0] - half_size[0],
      center[0] + half_size[0],
      center[2] - half_size[2],
      center[2] + half_size[2],
    )

  def _robot_state(self):
    torso_pos = self._env0(self.mj_data.xpos, self.body_id)
    quat_wxyz = self._env0(self.mj_data.xquat, self.body_id)
    rotation = R.from_quat(
      [quat_wxyz[1], quat_wxyz[2], quat_wxyz[3], quat_wxyz[0]]
    )
    attachment_pos = torso_pos + rotation.apply(self.attachment_pos_b)
    robot_com = self._env0(self.mj_data.subtree_com, self.robot_root_id)
    body_com = self._env0(self.mj_data.xipos, self.body_id)
    torso_euler = rotation.as_euler("xyz", degrees=False)
    self.torso_roll = float(torso_euler[0])
    pitch = torso_euler[1]
    root_quat_wxyz = self._env0(self.mj_data.xquat, self.robot_root_id)
    root_rotation = R.from_quat(
      [root_quat_wxyz[1], root_quat_wxyz[2], root_quat_wxyz[3], root_quat_wxyz[0]]
    )
    self.torso_relative_rpy = (
      root_rotation.inv() * rotation
    ).as_euler("xyz", degrees=False)
    yaw = root_rotation.as_euler("xyz", degrees=False)[2]
    if self.previous_yaw is not None:
      yaw_rate = self._wrap_to_pi(yaw - self.previous_yaw) / self.dt
      self.filtered_yaw_rate += 0.2 * (yaw_rate - self.filtered_yaw_rate)
    self.previous_yaw = yaw
    vz = 0.0
    if self.previous_attachment_z is not None:
      vz = (attachment_pos[2] - self.previous_attachment_z) / self.dt
    self.previous_attachment_z = attachment_pos[2]
    self.filtered_lift_velocity += self.velocity_filter_alpha * (
      vz - self.filtered_lift_velocity
    )
    vz = self.filtered_lift_velocity
    return robot_com, body_com, attachment_pos, rotation, pitch, yaw, vz

  def _set_phase(self, phase):
    if phase != self.phase:
      old_phase = self.PHASE_NAMES[self.phase]
      self.phase = phase
      self.phase_start_step = self.step_counter
      print(
        f"[WIRE] phase {old_phase} -> {self.PHASE_NAMES[phase]} "
        f"(t={self.step_counter * self.dt:.2f}s)",
        flush=True,
      )

  def _phase_time(self):
    return (self.step_counter - self.phase_start_step) * self.dt

  def crouch_policy_schedule(self):
    """Return walking/crouch blend and normalized crouch-depth commands."""
    if (
      self.external_crouch_policy
      and self.phase == self.PHASE_LIFT
      and not self.wide_posture_ready
    ):
      # Retain closed-loop crouch balance until cable support is established,
      # then the fixed suspension posture takes over.
      self.external_crouch_blend = 1.0
      self.external_crouch_depth = self.gap_crouch_depth
      return 1.0, self.gap_crouch_depth
    if (
      not self.external_crouch_policy
      or self.phase != self.PHASE_SETTLE
    ):
      self.external_crouch_blend = 0.0
      self.external_crouch_depth = 0.0
      return 0.0, 0.0

    phase_time = self._phase_time()
    handover_start = self.gap_crouch_wait_time
    crouch_start = handover_start + self.gap_policy_handover_time
    if phase_time < handover_start:
      blend = 0.0
      depth = 0.0
    elif phase_time < crouch_start:
      u = np.clip(
        (phase_time - handover_start)
        / max(self.gap_policy_handover_time, self.dt),
        0.0,
        1.0,
      )
      # Zero endpoint slopes prevent a step in action velocity at handover.
      blend = float(u * u * (3.0 - 2.0 * u))
      depth = 0.0
    else:
      blend = 1.0
      depth = self.gap_crouch_depth * float(
        np.clip(
          (phase_time - crouch_start)
          / max(self.gap_crouch_blend_time, self.dt),
          0.0,
          1.0,
        )
      )
    self.external_crouch_blend = blend
    self.external_crouch_depth = depth
    return blend, depth

  def _legacy_desired_tension_unused(
    self, robot_com, body_com, attachment_pos, pitch, vz
  ):
    """Deprecated controller retained temporarily for parameter comparison only."""
    box_front, box_back, box_bottom, box_top = self._obstacle_bounds()
    x = attachment_pos[0]
    if self.nominal_attachment_z is None:
      self.nominal_attachment_z = attachment_pos[2]
    if self.nominal_com_z is None:
      self.nominal_com_z = robot_com[2]
    target_z = self.nominal_attachment_z + (box_top - box_bottom) + self.clearance

    if self.phase == self.PHASE_APPROACH and x >= box_front - self.approach_distance:
      self._set_phase(self.PHASE_SETTLE)
    pre_lift_time = max(
      self.settle_time,
      self.brace_start_time + self.brace_blend_time,
    )
    gap_crouch_length_settled = (
      self.traversal_mode != "gap"
      or abs(actual_length - self.commanded_wire_length)
      <= self.wire_length_tolerance
    )
    if (
      self.phase == self.PHASE_SETTLE
      and self._phase_time() >= pre_lift_time
      and gap_crouch_length_settled
    ):
      self._set_phase(self.PHASE_LIFT)
    if self.phase == self.PHASE_LIFT:
      lifted_over_box = attachment_pos[2] >= target_z and x >= box_front
      if (lifted_over_box and self._phase_time() >= self.lift_min_hold_time) or (
        self._phase_time() >= self.lift_max_hold_time
      ):
        self._set_phase(self.PHASE_CROSS)
    if self.phase == self.PHASE_CROSS and self._phase_time() >= self.cross_hold_time:
      self._set_phase(self.PHASE_LOWER)
    if self.phase == self.PHASE_LOWER and self._phase_time() >= self.release_time:
      self._set_phase(self.PHASE_DONE)

    cable = self.anchor_pos - attachment_pos
    actual_length = float(np.linalg.norm(cable))
    if actual_length < 1e-6:
      return 0.0

    if self.wire_length is None:
      self.wire_length = actual_length
      self.commanded_wire_length = actual_length
      self.initial_wire_length = actual_length

    previous_actual_length = self.wire_length
    previous_commanded_length = self.commanded_wire_length
    self.wire_length = actual_length

    if self.phase == self.PHASE_APPROACH:
      # Before the obstacle the winch pays out freely, so the cable stays slack.
      self.commanded_wire_length = actual_length
      self.initial_wire_length = actual_length
    elif self.phase in (self.PHASE_LIFT, self.PHASE_CROSS):
      minimum_length = self.initial_wire_length - self.max_reel_in
      self.commanded_wire_length = max(
        minimum_length,
        self.commanded_wire_length - self.reel_in_speed * self.dt,
      )
    elif self.phase == self.PHASE_LOWER:
      self.commanded_wire_length = min(
        self.initial_wire_length,
        self.commanded_wire_length + self.payout_speed * self.dt,
      )
    elif self.phase == self.PHASE_DONE:
      self.commanded_wire_length = actual_length

    # The rear attachment creates a forward pitching moment.  If the torso
    # starts pitching forward, stop reel-in and pay cable out instead.
    if pitch > self.pitch_soft_limit and self.phase in (
      self.PHASE_LIFT,
      self.PHASE_CROSS,
    ):
      self.commanded_wire_length = min(
        self.initial_wire_length,
        max(self.commanded_wire_length, previous_commanded_length)
        + self.pitch_payout_speed * self.dt,
      )

    actual_length_rate = (actual_length - previous_actual_length) / self.dt
    commanded_length_rate = (
      self.commanded_wire_length - previous_commanded_length
    ) / self.dt
    extension = max(0.0, actual_length - self.commanded_wire_length)
    extension_rate = actual_length_rate - commanded_length_rate
    target_tension = self.winch_kp * extension + self.winch_kd * extension_rate

    # Length control alone can go slack as the robot follows the cable.  During
    # lifting, add the exact cable tension needed to balance gravity, then close
    # the loop on vertical velocity so the body rises at a controlled speed.
    if self.phase == self.PHASE_LIFT:
      vertical_direction = max(cable[2] / actual_length, 0.10)
      hover_tension = self.robot_weight / vertical_direction
      velocity_tension = self.lift_velocity_kp * (self.lift_target_velocity - vz)
      target_tension = max(target_tension, hover_tension + velocity_tension)
    pitch_scale = np.clip(
      (self.pitch_hard_limit - pitch)
      / (self.pitch_hard_limit - self.pitch_soft_limit),
      0.0,
      1.0,
    )
    target_tension *= pitch_scale

    # The cable cannot push; SETTLE intentionally leaves it slack before reel-in.
    if self.phase in (self.PHASE_APPROACH, self.PHASE_SETTLE, self.PHASE_DONE):
      return 0.0
    return float(np.clip(target_tension, 0.0, self.max_tension))

  def _apply_cable_force(self, body_com, attachment_pos, desired_tension):
    tension_limit = (
      self.ascend_max_tension
      if self.traversal_mode == "ascend"
      else self.max_tension
    )
    limited_target = float(np.clip(desired_tension, 0.0, tension_limit))
    # Active hoisting/lowering needs enough bandwidth to brake oscillation.
    # Only the final RELEASE uses the deliberately gentle force ramp-down.
    if self.phase == self.PHASE_SETTLE and self.traversal_mode == "gap":
      rate_limit = self.gap_crouch_tension_rate
    elif self.phase == self.PHASE_LIFT and self.traversal_mode == "gap":
      # A far-side anchor has a large horizontal force component.  Bringing
      # the cable load up slowly avoids an impulse that pitches and yaws the
      # suspended robot before its fixed posture can react.
      rate_limit = self.gap_lift_tension_rate
    elif self.phase == self.PHASE_RELEASE and limited_target < self.tension:
      rate_limit = self.tension_release_rate
    else:
      rate_limit = self.tension_rate
    max_delta = rate_limit * self.dt
    self.tension += float(
      np.clip(limited_target - self.tension, -max_delta, max_delta)
    )
    self.desired_tension = limited_target
    cable = self.anchor_pos - attachment_pos
    cable_length = np.linalg.norm(cable)
    force = np.zeros(3) if cable_length < 1e-6 else self.tension * cable / cable_length
    # Apply only the moment generated by the real rear attachment point.
    torque = np.cross(attachment_pos - body_com, force)
    wrench = np.concatenate((force, torque)).astype(np.float32)

    xfrc = self.mj_data.xfrc_applied
    target = xfrc[0, self.body_id] if len(xfrc.shape) == 3 else xfrc[self.body_id]
    if hasattr(target, "copy_"):
      target.copy_(torch.as_tensor(wrench, device=target.device, dtype=target.dtype))
    else:
      target[:] = wrench

  def _update_waist_diagnostics(self):
    """Read waist state through Entity indexing; never write qfrc_applied."""
    joint_pos = self.robot_entity.data.joint_pos
    for axis in ("yaw", "roll", "pitch"):
      joint_id = self.waist_entity_joint_ids.get(axis, -1)
      if joint_id < 0:
        self.waist_angles[axis] = 0.0
        self.waist_torques[axis] = 0.0
        continue
      self.waist_angles[axis] = float(joint_pos[0, joint_id].item())
      self.waist_torques[axis] = 0.0

    self.waist_roll_angle = self.waist_angles["roll"]
    self.waist_roll_torque = 0.0

  def _configure_descent_wire_targets(
    self,
    attachment_pos,
    actual_length,
    box_bottom,
    box_top,
    announce=False,
    from_crouch=False,
  ):
    """Update preload from the crouch while preserving the landing geometry."""
    self.target_wire_length = max(
      actual_length - self.descent_preload_reel_in,
      0.05,
    )
    attachment_height_above_support = max(
      attachment_pos[2] - box_top,
      0.0,
    )
    ground_attachment_z = box_bottom + attachment_height_above_support
    computed_landing_length = (
      self.anchor_pos[2]
      - ground_attachment_z
      + self.descent_landing_length_margin
    )
    if not from_crouch or self.descent_nominal_landing_length is None:
      self.descent_nominal_landing_length = (
        computed_landing_length
        if self.descent_release_wire_length is None
        else float(self.descent_release_wire_length)
      )
    self.release_target_wire_length = max(
      self.descent_nominal_landing_length,
      self.target_wire_length,
    )
    if announce:
      print(
        "[WIRE] descent profile armed"
        f" ({'crouched' if from_crouch else 'standing'} geometry): "
        f"Lpreload={self.target_wire_length:.3f}m "
        f"Llanding={self.release_target_wire_length:.3f}m",
        flush=True,
      )

  def _configure_ascend_wire_targets(
    self,
    actual_length,
    announce=False,
    from_crouch=False,
  ):
    """Preserve the standing reel/payout travel after crouching.

    Crouching lowers the rear attachment and changes its geometric distance to
    the ceiling anchor.  The traversal objective is the amount reeled in, not
    one world-specific absolute cable length, so measure that travel in the
    standing pose and apply it again from the crouched cable length.
    """
    if (
      not from_crouch
      or self.ascend_nominal_hoist_reel_in is None
      or self.ascend_nominal_payout is None
    ):
      target = max(
        min(self.hoist_target_wire_length, actual_length),
        0.05,
      )
      release = (
        actual_length
        if self.configured_release_target_wire_length is None
        else max(
          float(self.configured_release_target_wire_length),
          target,
        )
      )
      self.ascend_nominal_hoist_reel_in = max(actual_length - target, 0.0)
      self.ascend_nominal_payout = max(release - target, 0.0)

    self.target_wire_length = max(
      actual_length - self.ascend_nominal_hoist_reel_in,
      0.05,
    )
    self.release_target_wire_length = max(
      self.target_wire_length + self.ascend_nominal_payout,
      self.target_wire_length,
    )
    if announce:
      print(
        "[WIRE] ascend profile armed"
        f" ({'crouched' if from_crouch else 'standing'} geometry): "
        f"Lstart={actual_length:.3f}m "
        f"Lhoist={self.target_wire_length:.3f}m "
        f"Lrelease={self.release_target_wire_length:.3f}m "
        f"reel={self.ascend_nominal_hoist_reel_in:.3f}m "
        f"payout={self.ascend_nominal_payout:.3f}m",
        flush=True,
      )

  def _configure_gap_wire_targets(
    self,
    attachment_pos,
    actual_length,
    box_top,
    announce=False,
    from_crouch=False,
  ):
    """Derive hoist and landing lengths for a supported Tarzan arc.

    The robot first gains horizontal motion like a pendulum, while controlled
    reel-in compensates for the vertical drop that would otherwise put its feet
    on the gap floor.  The landing length restores the crouched foot height on
    the equal-height far platform.  Explicit lengths remain available.
    """
    attachment_height = max(float(attachment_pos[2] - box_top), 0.05)
    landing_attachment_z = (
      box_top + attachment_height - self.gap_landing_length_margin
    )
    computed_landing_length = max(
      float(self.anchor_pos[2] - landing_attachment_z),
      0.05,
    )
    computed_hoist_length = max(
      computed_landing_length - self.gap_hoist_clearance,
      0.05,
    )
    base_hoist = (
      computed_hoist_length
      if self.gap_hoist_wire_length is None
      else float(self.gap_hoist_wire_length)
    )
    base_landing = (
      computed_landing_length
      if self.gap_release_wire_length is None
      else float(self.gap_release_wire_length)
    )
    requested_hoist = base_hoist + self.gap_hoist_wire_length_offset
    requested_landing = (
      base_landing + self.gap_release_wire_length_offset
    )
    self.target_wire_length = max(
      min(requested_hoist, actual_length),
      0.05,
    )
    self.release_target_wire_length = max(
      requested_landing,
      self.target_wire_length,
    )
    self.gap_nominal_hoist_reel_in = max(
      actual_length - self.target_wire_length,
      0.0,
    )
    self.gap_nominal_payout = max(
      self.release_target_wire_length - self.target_wire_length,
      0.0,
    )
    if announce:
      print(
        "[WIRE] gap profile armed"
        f" ({'crouched' if from_crouch else 'standing'} geometry): "
        f"Lstart={actual_length:.3f}m "
        f"Lhoist={self.target_wire_length:.3f}m "
        f"Llanding={self.release_target_wire_length:.3f}m "
        f"h_attach={attachment_height:.3f}m "
        f"offsets=({self.gap_hoist_wire_length_offset:+.3f},"
        f"{self.gap_release_wire_length_offset:+.3f})m "
        f"reel={self.gap_nominal_hoist_reel_in:.3f}m "
        f"payout={self.gap_nominal_payout:.3f}m",
        flush=True,
      )

  def _suspension_posture_profile(self):
    """Return mode-specific posture values without changing the state graph."""
    if self.traversal_mode == "descend":
      return (
        "descent_feet_down",
        self.descent_posture_action,
        self.descent_posture_blend_time,
        self.descent_posture_action_rate_limit,
      )
    if self.traversal_mode == "gap":
      return (
        "gap_suspension",
        self.gap_posture_action,
        self.gap_posture_blend_time,
        self.gap_posture_action_rate_limit,
      )
    return (
      "wide_lift",
      self.lift_posture_action,
      self.wide_posture_blend_time,
      self.wide_posture_action_rate_limit,
    )

  def _inextensible_cable_tension(self, attachment_pos):
    """Reel an inextensible cable at constant speed to a fixed hoist length."""
    box_front, box_back, box_bottom, box_top = self._obstacle_bounds()
    cable = self.anchor_pos - attachment_pos
    actual_length = float(np.linalg.norm(cable))
    if actual_length < 1e-6:
      return 0.0

    if self.wire_length is None:
      self.wire_length = actual_length
      self.commanded_wire_length = actual_length
      self.initial_wire_length = actual_length
    previous_actual = self.wire_length
    previous_commanded = self.commanded_wire_length
    self.wire_length = actual_length

    if self.phase == self.PHASE_APPROACH:
      self.commanded_wire_length = actual_length
      self.initial_wire_length = actual_length
      approach_edge = (
        box_back if self.traversal_mode == "descend" else box_front
      )
      approach_distance = (
        self.descent_approach_distance
        if self.traversal_mode == "descend"
        else (
          self.gap_approach_distance
          if self.traversal_mode == "gap"
          else self.approach_distance
        )
      )
      if attachment_pos[0] >= approach_edge - approach_distance:
        if self.traversal_mode == "descend":
          # Preload the cable without hoisting the robot high above the top
          # surface.  The forward-offset anchor then transfers the suspended
          # body beyond the edge before controlled payout begins.
          self._configure_descent_wire_targets(
            attachment_pos,
            self.initial_wire_length,
            box_bottom,
            box_top,
            announce=True,
          )
        elif self.traversal_mode == "gap":
          self._configure_gap_wire_targets(
            attachment_pos,
            self.initial_wire_length,
            box_top,
            announce=True,
          )
        else:
          self._configure_ascend_wire_targets(
            self.initial_wire_length,
            announce=True,
          )
        self._set_phase(self.PHASE_SETTLE)

    if self.phase == self.PHASE_SETTLE:
      if self.traversal_mode == "gap":
        if self._phase_time() < self.gap_crouch_wait_time:
          # First let the zero-velocity policy finish braking at the edge.  Any
          # tension here has a forward component toward the far-side anchor and
          # was the direct cause of the robot being dragged off its stance.
          self.commanded_wire_length = actual_length
        else:
          if self.gap_crouch_command_target is None:
            print(
              "[WIRE] gap crouch follows measured slack length; "
              "no absolute payout wait",
              flush=True,
            )
          # Follow crouch geometry with a slack command, then freeze the final
          # measured length at LIFT.  Hoist/landing targets are computed there.
          self.gap_crouch_command_target = actual_length
          self.commanded_wire_length = actual_length
      else:
        # Other modes retain a slack cable while the standing policy settles.
        self.commanded_wire_length = actual_length
      self.initial_wire_length = actual_length
      if (
        self.traversal_mode == "ascend"
        and self.configured_release_target_wire_length is None
      ):
        self.release_target_wire_length = actual_length

    crouch_sequence_time = (
      self.gap_crouch_wait_time
      + self.gap_policy_handover_time
      + self.gap_crouch_blend_time
      + self.gap_crouch_settle_time
    )
    pre_lift_time = (
      crouch_sequence_time
      if self.external_crouch_policy
      else (
        self.gap_crouch_wait_time
        + self.gap_crouch_blend_time
        + self.gap_crouch_settle_time
        if self.traversal_mode == "gap"
        else max(
          self.settle_time,
          self.brace_start_time + self.brace_blend_time,
        )
      )
    )
    crouch_wire_ready = (
      self.traversal_mode != "gap"
      or (
        self.gap_crouch_command_target is not None
        and abs(
          self.commanded_wire_length - self.gap_crouch_command_target
        ) <= self.wire_length_tolerance
      )
    )
    if (
      self.phase == self.PHASE_SETTLE
      and self._phase_time() >= pre_lift_time
      and crouch_wire_ready
    ):
      # Use the measured taut length as the new LIFT datum.  This removes the
      # small fall-arrester extension that can accumulate during SETTLE.
      self.initial_wire_length = actual_length
      self.commanded_wire_length = actual_length
      self.lift_start_wire_length = self.commanded_wire_length
      if self.traversal_mode == "descend":
        self._configure_descent_wire_targets(
          attachment_pos,
          actual_length,
          box_bottom,
          box_top,
          announce=True,
          from_crouch=True,
        )
      elif self.traversal_mode == "gap":
        self._configure_gap_wire_targets(
          attachment_pos,
          self.commanded_wire_length,
          box_top,
          announce=True,
          from_crouch=True,
        )
      else:
        self._configure_ascend_wire_targets(
          actual_length,
          announce=True,
          from_crouch=True,
        )
      self._set_phase(self.PHASE_LIFT)

    if self.phase == self.PHASE_LIFT:
      # Decelerate the winch command before the target.  A cable cannot push the
      # robot back down after an overshoot, so arriving with near-zero radial
      # velocity is essential.
      remaining = max(self.commanded_wire_length - self.target_wire_length, 0.0)
      reel_speed = min(
        (
          self.descent_reel_in_speed
          if self.traversal_mode == "descend"
          else (
            self.gap_reel_in_speed
            if self.traversal_mode == "gap"
            else self.reel_in_speed
          )
        ),
        np.sqrt(
          2.0
          * (
            self.gap_reel_in_acceleration
            if self.traversal_mode == "gap"
            else self.wire_acceleration
          )
          * remaining
        ),
      )
      if (
        self.traversal_mode == "gap"
        and self._phase_time() < self.gap_lift_preload_time
      ):
        # First transfer the load from the feet to the cable.  Reeling while
        # tension is still ramping creates a large stored length error and a
        # delayed snap once the robot leaves the platform.
        reel_speed = 0.0
      self.commanded_wire_length = max(
        self.target_wire_length,
        self.commanded_wire_length - reel_speed * self.dt,
      )

    hold_time = (
      self.descent_hold_time
      if self.traversal_mode == "descend"
      else (
        self.gap_hold_time
        if self.traversal_mode == "gap"
        else self.cross_hold_time
      )
    )
    if self.phase == self.PHASE_CROSS and self._phase_time() >= hold_time:
      self._set_phase(self.PHASE_LOWER)
    if self.phase == self.PHASE_LOWER:
      # Keep the cable taut while paying it out.  The same length constraint
      # used for hoisting therefore brakes the descent instead of dropping the
      # robot under gravity.
      release_length = self.release_target_wire_length or self.initial_wire_length
      remaining = max(release_length - self.commanded_wire_length, 0.0)
      payout_speed = min(
        (
          self.descent_payout_speed
          if self.traversal_mode == "descend"
          else (
            self.gap_payout_speed
            if self.traversal_mode == "gap"
            else self.payout_speed
          )
        ),
        np.sqrt(
          2.0
          * (
            self.descent_payout_acceleration
            if self.traversal_mode == "descend"
            else (
              self.gap_payout_acceleration
              if self.traversal_mode == "gap"
              else self.payout_acceleration
            )
          )
          * remaining
        ),
      )
      self.commanded_wire_length = min(
        release_length,
        self.commanded_wire_length + payout_speed * self.dt,
      )
      command_finished = self.commanded_wire_length >= release_length - 1e-6
      if command_finished and self.lower_command_complete_step is None:
        self.lower_command_complete_step = self.step_counter
    if self.phase == self.PHASE_RELEASE:
      # Once the slow payout is complete, ramp the tension down through the
      # common tension-rate limiter.  DONE is selected after force application.
      self.commanded_wire_length = (
        self.release_target_wire_length or self.initial_wire_length
      )
    if self.phase == self.PHASE_ASSIST:
      # Keep the cable at the landing length while the standing policy is
      # blended back in.  The cable continues supporting the robot here.
      self.commanded_wire_length = (
        self.release_target_wire_length or self.initial_wire_length
      )
      assisted_policy_hold_time = (
        self.descent_assisted_policy_hold_time
        if self.traversal_mode == "descend"
        else self.assisted_policy_hold_time
      )
      if self._phase_time() >= max(
        assisted_policy_hold_time,
        self.policy_resume_blend_time,
      ):
        self._set_phase(self.PHASE_RELEASE)
    if self.phase == self.PHASE_DONE:
      self.commanded_wire_length = actual_length

    actual_rate = (actual_length - previous_actual) / self.dt
    commanded_rate = (self.commanded_wire_length - previous_commanded) / self.dt
    self.filtered_wire_rate += self.wire_rate_filter_alpha * (
      actual_rate - self.filtered_wire_rate
    )
    self.commanded_wire_rate = commanded_rate
    length_error = actual_length - self.commanded_wire_length
    rate_error = self.filtered_wire_rate - commanded_rate
    vertical_fraction = max(cable[2] / actual_length, 0.05)
    gap_crouch_support = (
      self.traversal_mode == "gap" and self.phase == self.PHASE_SETTLE
    )
    gap_swing = (
      self.traversal_mode == "gap"
      and self.phase in (self.PHASE_LIFT, self.PHASE_CROSS)
    )
    if gap_swing:
      # Tarzan motion: keep the cable inextensible without cancelling gravity.
      # For a body initially at rest on a cable, the radial gravity component
      # is mg*u_z (not mg/u_z, which creates an excessive horizontal pull).
      # Signed constraint terms suppress stretch/radial velocity while gravity's
      # tangential component naturally drives the swing across the gap.
      tension = (
        self.robot_weight * vertical_fraction
        + self.gap_constraint_kp * length_error
        + self.gap_constraint_kd * rate_error
      )
    elif not gap_crouch_support:
      # Match the stable dev/g1_wire/dev/down hoist controller.  Gravity support
      # is the feed-forward baseline; signed errors continuously add or remove
      # tension around it.  The one-sided law made hoisting alternate between
      # 0 and max tension whenever the body crossed Lcmd, exciting its radial
      # mode.  Use this continuously during LIFT/HOLD/LOWER for every traversal.
      tension = (
        self.robot_weight / vertical_fraction
        + self.constraint_kp * length_error
        + self.constraint_kd * rate_error
      )
    else:
      # During the gap SETTLE crouch, both feet remain planted and the far-side
      # cable must act only as a one-sided fall arrester to avoid dragging them.
      taut_scale = float(
        np.clip(
          (length_error + self.cable_taut_transition)
          / max(self.cable_taut_transition, 1e-6),
          0.0,
          1.0,
        )
      )
      tension = (
        taut_scale * self.robot_weight / vertical_fraction
        + self.constraint_kp * max(length_error, 0.0)
        + self.constraint_kd * max(rate_error, 0.0)
      )

    if self.phase == self.PHASE_SETTLE and self.traversal_mode == "gap":
      # Stay completely slack until the standing policy has stopped the robot.
      # The far-side anchor necessarily produces forward force whenever the
      # cable is taut, so unconditional preload is unsafe while feet are down.
      if (
        self._phase_time() < self.gap_crouch_wait_time
        or self.gap_crouch_command_target is None
      ):
        return 0.0

      # Once crouching starts, engage only after the geometric distance exceeds
      # the paid-out length plus a small slack allowance.  This makes the cable
      # a one-sided fall arrester rather than a device that drags the feet.
      supported_extension = max(
        length_error - self.gap_crouch_support_slack,
        0.0,
      )
      if supported_extension <= 0.0:
        return 0.0
      crouch_tension = (
        self.gap_crouch_preload_tension
        + self.constraint_kp * supported_extension
        + self.constraint_kd * max(rate_error, 0.0)
      )

      # Limit the horizontal component directly.  This remains meaningful if
      # the anchor or edge position changes and is the quantity that determines
      # whether planted feet slide toward the gap.
      horizontal_fraction = float(np.linalg.norm(cable[:2]) / actual_length)
      horizontal_tension_limit = (
        self.gap_crouch_max_tension
        if horizontal_fraction < 1e-6
        else self.gap_crouch_max_horizontal_force / horizontal_fraction
      )
      return float(
        np.clip(
          crouch_tension,
          0.0,
          min(self.gap_crouch_max_tension, horizontal_tension_limit),
        )
      )

    # Do not start the hold timer while the body is still flying through the
    # target.  Both cable length and radial speed must have settled.
    if self.phase == self.PHASE_LIFT:
      # A descent body can swing inside the commanded cable-length sphere after
      # its short preload.  The cable cannot push it back outward, so accept a
      # settled undershoot; requiring |L-Lcmd| here left LIFT active forever.
      length_settled = (
        length_error <= self.hold_length_tolerance
        if self.traversal_mode == "descend"
        else abs(length_error) <= self.hold_length_tolerance
      )
      rate_settled = abs(self.filtered_wire_rate) <= self.hold_rate_tolerance
      command_finished = self.commanded_wire_length <= self.target_wire_length + 1e-6
      gap_crossed = (
        self.traversal_mode != "gap"
        or (
          self.gap_swing_landing_x is not None
          and attachment_pos[0] >= self.gap_swing_landing_x - 0.05
        )
      )
      if (
        command_finished
        and length_settled
        and rate_settled
        and gap_crossed
        and self.wide_posture_ready
      ):
        self._set_phase(self.PHASE_CROSS)
    elif self.phase == self.PHASE_LOWER:
      release_delay_elapsed = (
        self.lower_command_complete_step is not None
        and (self.step_counter - self.lower_command_complete_step) * self.dt
        >= self.lower_release_delay
      )
      if release_delay_elapsed:
        self._set_phase(self.PHASE_ASSIST)
    if self.phase in (
      self.PHASE_APPROACH,
      self.PHASE_SETTLE,
      self.PHASE_RELEASE,
      self.PHASE_DONE,
    ):
      return 0.0
    return max(float(tension), 0.0)

  def _log_wire_state(self, attachment_pos, vz):
    interval_steps = max(1, int(round(self.log_interval / self.dt)))
    if self.last_log_step >= 0 and self.step_counter - self.last_log_step < interval_steps:
      return
    self.last_log_step = self.step_counter
    commanded = self.commanded_wire_length
    target = self.target_wire_length
    print(
      f"[WIRE] t={self.step_counter * self.dt:7.2f}s "
      f"phase={self.PHASE_NAMES[self.phase]:8s} "
      f"L={self.wire_length if self.wire_length is not None else float('nan'):.3f}m "
      f"Lcmd={commanded if commanded is not None else float('nan'):.3f}m "
      f"Ltarget={target if target is not None else float('nan'):.3f}m "
      f"Lrelease={self.release_target_wire_length if self.release_target_wire_length is not None else float('nan'):.3f}m "
      f"Lcrouch={self.gap_crouch_command_target if self.gap_crouch_command_target is not None else self.gap_crouch_wire_length:.3f}m "
      f"Ldot={self.filtered_wire_rate:+.3f}m/s "
      f"Ldot_cmd={self.commanded_wire_rate:+.3f}m/s "
      f"T={self.tension:6.1f}/{self.desired_tension:6.1f}N "
      f"yaw_err={np.rad2deg(self.heading_error):+.1f}deg "
      f"yaw_rate={np.rad2deg(self.filtered_yaw_rate):+.1f}deg/s "
      f"roll={np.rad2deg(self.torso_roll):+.1f}deg "
      f"waist_ypr=({np.rad2deg(self.waist_angles['yaw']):+.1f},"
      f"{np.rad2deg(self.waist_angles['pitch']):+.1f},"
      f"{np.rad2deg(self.waist_angles['roll']):+.1f})deg "
      f"waist_extra_tau=({self.waist_torques['yaw']:+.1f},"
      f"{self.waist_torques['pitch']:+.1f},"
      f"{self.waist_torques['roll']:+.1f})Nm "
      f"waist_lock={'ON' if self.waist_lock_active else 'OFF'} "
      f"posture={self.posture_mode or 'policy'} "
      f"crouch_mix={self.external_crouch_blend:.2f} "
      f"crouch_depth={self.external_crouch_depth:.2f} "
      f"Lreel={self.lift_start_wire_length - self.commanded_wire_length if self.lift_start_wire_length is not None and self.commanded_wire_length is not None else 0.0:+.3f}m "
      f"wide={'ON' if self.wide_posture_ready else 'OFF'} "
      f"torso_rel_rpy=({np.rad2deg(self.torso_relative_rpy[0]):+.1f},"
      f"{np.rad2deg(self.torso_relative_rpy[1]):+.1f},"
      f"{np.rad2deg(self.torso_relative_rpy[2]):+.1f})deg "
      f"z_back={attachment_pos[2]:.3f}m "
      f"vz={vz:+.3f}m/s",
      flush=True,
    )

