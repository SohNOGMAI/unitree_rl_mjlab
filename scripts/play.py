class WireAssistWrapper:
  """Obstacle-aware cable tension controller, independent of the walking policy.

  The cable is massless and can only pull toward a fixed world-space anchor.  MuJoCo's
  ``xfrc_applied`` acts at a body's centre of mass, so the moment generated by the
  rear-back attachment point is explicitly added as ``r x F``.
  """

  (
    PHASE_APPROACH,
    PHASE_SETTLE,
    PHASE_LIFT,
    PHASE_CROSS,
    PHASE_LOWER,
    PHASE_DONE,
  ) = range(6)

